#!/usr/bin/env node
// REFERENCE IMPLEMENTATION — adapt before dropping into a target repo.
// Validated, lint-clean (incl. SonarQube) on a Node/npm/ESM repo. Adapt the
// ADAPT-marked lines to the target repo's actual changelog directory, task-
// runner naming, and (if not Node) reimplement using this as a spec.
//
// Regenerates <changelog-dir>/INDEX.md from the frontmatter of every entry.
// The index is a generated artifact — never hand-edit it.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml"; // ADAPT: reuse repo's existing YAML dep if one exists

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), ".."); // ADAPT: path to repo root from this script's location
const CHANGELOG_DIR = join(ROOT, "docs/changelog"); // ADAPT: target repo's actual changelog directory
const INDEX_PATH = join(CHANGELOG_DIR, "INDEX.md");

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  try {
    return parseYaml(match[1]);
  } catch {
    return null;
  }
}

// ADAPT: assumes the entry's H1 first token (up to the first space) is the
// id — issue-id-only or issue-id-plus-sequence-number, no internal space either
// way — and everything after that space is the title. In Scenario B/C
// (SKILL.md Phase 0) this was
// already validated against an existing template. In Scenario A, SKILL.md
// Phase 1 question 3 chooses this shape fresh — if that answer picks
// anything else, rewrite this whole function's return line to match; the
// split-heading-line approach below
// (not a single regex with two adjacent variable-length quantifiers, `\s+`
// then `.+`) is still worth keeping — that regex shape gets flagged by
// static analysis (SonarQube S8786) as super-linear backtracking risk, and
// plain string ops are simpler anyway.
function parseTitle(content) {
  const withoutFrontmatter = content.replace(/^---\n[\s\S]*?\n---\n/, "");
  const headingLine = withoutFrontmatter.split("\n").find((line) => line.startsWith("# "));
  if (!headingLine) return "";
  const headingText = headingLine.slice(2).trim();
  const spaceIndex = headingText.indexOf(" ");
  return spaceIndex === -1 ? headingText : headingText.slice(spaceIndex + 1).trim();
}

function buildRow(file, frontmatter, title) {
  const { issue, date, paths, tags = [] } = frontmatter; // ADAPT: field names, if the target schema differs
  const tagList = Array.isArray(tags) ? tags : [];
  const pathList = Array.isArray(paths) ? paths : [];
  return {
    file,
    date,
    issue,
    title: title || file,
    tags: tagList,
    paths: pathList,
  };
}

function main() {
  const files = readdirSync(CHANGELOG_DIR).filter((f) => f.endsWith(".md") && f !== "INDEX.md");

  const rows = [];
  for (const file of files) {
    const content = readFileSync(join(CHANGELOG_DIR, file), "utf8");
    const frontmatter = parseFrontmatter(content);
    if (!frontmatter?.issue || !frontmatter?.date || !frontmatter?.paths) {
      // Skip + warn, never hard-fail — this is what makes lazy/incremental
      // backfill safe: an entry with no frontmatter yet just doesn't appear
      // in the index until it's backfilled, instead of breaking the build.
      console.warn(`dev-changelog:index: skipping ${file} — missing or invalid frontmatter`);
      continue;
    }
    rows.push(buildRow(file, frontmatter, parseTitle(content)));
  }

  rows.sort((a, b) => {
    if (a.date !== b.date) return a.date < b.date ? 1 : -1;
    return a.file.localeCompare(b.file); // never a bare .sort() — flagged even for plain strings
  });

  const knownTags = [...new Set(rows.flatMap((r) => r.tags))].sort((a, b) => a.localeCompare(b));

  // ADAPT: every "npm run ..." command named in this block (3 occurrences
  // below) — all of them, not just the first — to match the target repo's
  // actual task-runner invocation. Left as npm here only because the
  // original build was an npm repo; a leftover npm command in a non-npm
  // repo's generated docs is wrong every time a reader tries to run it.
  const lines = [
    "# Changelog Index",
    "",
    "Generated by `npm run dev-changelog:index` from the frontmatter of every file in this",
    "directory — do not hand-edit the table. Query it with `npm run search:dev-changelog --",
    "<path-or-tag>`.",
    "",
    `Known tags (prefer reusing one — \`npm run search:dev-changelog -- --tags\` lists what's`,
    `actually in use): ${knownTags.join(", ")}.`,
    "",
    "| Date | Issue | Entry | Tags | Paths |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => {
      const entry = `[${r.title}](./${r.file})`;
      const tags = r.tags.join(", ");
      const paths = r.paths.map((p) => `\`${p}\``).join(", ");
      return `| ${r.date} | ${r.issue} | ${entry} | ${tags} | ${paths} |`;
    }),
    "",
  ];

  writeFileSync(INDEX_PATH, lines.join("\n"));
  console.log(`dev-changelog:index: wrote ${rows.length} entries to ${INDEX_PATH}`);
}

main();
